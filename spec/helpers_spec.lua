require("spec_helper")
local Helpers = require("helpers")

describe("Helpers.entryIdFromFilename", function()
    it("decodes the id from a download filename", function()
        assert.equals(1234, Helpers.entryIdFromFilename("[mf-id_1234] Some Article.epub"))
    end)
    it("returns nil when there is no prefix", function()
        assert.is_nil(Helpers.entryIdFromFilename("No prefix here.epub"))
    end)
    it("returns nil for a non-numeric id", function()
        assert.is_nil(Helpers.entryIdFromFilename("[mf-id_abc] Invalid.epub"))
    end)
end)

describe("Helpers.entryFilename", function()
    it("frames the id with the documented prefix/postfix", function()
        assert.equals("[mf-id_7] Title.epub", Helpers.entryFilename(7, "Title"))
    end)
    it("round-trips with entryIdFromFilename", function()
        local name = Helpers.entryFilename(42, "Hello World")
        assert.equals(42, Helpers.entryIdFromFilename(name))
    end)
end)

describe("Helpers.xmlEscape", function()
    it("escapes the XML-significant characters", function()
        assert.equals("&lt;a&gt; &amp; &quot;x&quot;", Helpers.xmlEscape('<a> & "x"'))
    end)
    it("returns an empty string for nil", function()
        assert.equals("", Helpers.xmlEscape(nil))
    end)
    it("leaves a plain string untouched", function()
        assert.equals("hello", Helpers.xmlEscape("hello"))
    end)
end)

describe("Helpers.apiErrorMessage", function()
    it("maps known error keywords to a message", function()
        assert.is_string(Helpers.apiErrorMessage("unauthorized"))
        assert.is_string(Helpers.apiErrorMessage("network_error"))
    end)
    it("returns nil for unknown keywords", function()
        assert.is_nil(Helpers.apiErrorMessage("http_error"))
        assert.is_nil(Helpers.apiErrorMessage(nil))
    end)
end)

describe("Helpers.defaultTrue", function()
    it("is true when the setting was never set (nil)", function()
        assert.is_true(Helpers.defaultTrue(nil))
    end)
    it("preserves an explicit false", function()
        assert.is_false(Helpers.defaultTrue(false))
    end)
    it("preserves an explicit true", function()
        assert.is_true(Helpers.defaultTrue(true))
    end)
end)

describe("Helpers.buildResultLines", function()
    it("returns no lines for an empty sync", function()
        assert.same({}, Helpers.buildResultLines({ marked = 0, removed = 0 }))
    end)
    it("includes the downloaded line whenever present, even at zero", function()
        local lines = Helpers.buildResultLines({ downloaded = 0 })
        assert.equals(1, #lines)
        assert.is_truthy(lines[1]:find("Downloaded 0 articles", 1, true))
    end)
    it("uses the singular form for a count of one", function()
        local lines = Helpers.buildResultLines({ downloaded = 1 })
        assert.is_truthy(lines[1]:find("Downloaded 1 article.", 1, true))
    end)
    it("omits skipped, failed, marked and removed when zero", function()
        local lines = Helpers.buildResultLines({
            downloaded = 2, skipped = 0, failed = 0, marked = 0, removed = 0,
        })
        assert.same({ "Downloaded 2 articles." }, lines)
    end)
    it("appends the optional counters in order when positive", function()
        local lines = Helpers.buildResultLines({
            downloaded = 3, skipped = 1, failed = 2, marked = 4, removed = 5,
        })
        assert.equals(5, #lines)
        assert.is_truthy(lines[2]:find("Skipped 1", 1, true))
        assert.is_truthy(lines[3]:find("Failed: 2", 1, true))
        assert.is_truthy(lines[4]:find("Marked 4 articles", 1, true))
        assert.is_truthy(lines[5]:find("Removed 5 articles", 1, true))
    end)
    it("adds the interruption line when cancelled", function()
        local lines = Helpers.buildResultLines({ downloaded = 0, cancelled = true })
        assert.is_truthy(lines[2]:find("interrupted", 1, true))
    end)
end)

describe("Helpers.buildArticleHtml", function()
    it("includes the title and content", function()
        local html = Helpers.buildArticleHtml({ title = "Hi", content = "<p>Body</p>" })
        assert.is_truthy(html:find("<title>Hi</title>", 1, true))
        assert.is_truthy(html:find("<article><p>Body</p></article>", 1, true))
    end)
    it("escapes the title but not the content", function()
        local html = Helpers.buildArticleHtml({ title = "A & B", content = "<p>x</p>" })
        assert.is_truthy(html:find("<title>A &amp; B</title>", 1, true))
        assert.is_truthy(html:find("<p>x</p>", 1, true))
    end)
    it("builds a byline from author, feed and date", function()
        local html = Helpers.buildArticleHtml({
            title = "T", author = "Jane",
            feed = { title = "Blog" }, published_at = "2026-01-02T03:04:05Z",
        })
        assert.is_truthy(html:find("Jane · Blog · 2026-01-02", 1, true))
    end)
    it("omits the source footer when there is no url", function()
        local html = Helpers.buildArticleHtml({ title = "T" })
        assert.is_nil(html:find("<hr/>", 1, true))
    end)
    it("adds a source link when a url is present", function()
        local html = Helpers.buildArticleHtml({ title = "T", url = "https://e.org/a" })
        assert.is_truthy(html:find('href="https://e.org/a"', 1, true))
    end)
end)
